import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const dashboard=read('src/commerce-commercial-dashboard.jsx');
const velocity=read('src/commerce-sales-velocity.jsx');
const abc=read('src/commerce-abc-ad-performance.jsx');
const sql=read('supabase/migrations/20261016073000_commerce_sales_velocity_v2_active_zero_only.sql');
const abcSql=read('supabase/migrations/20261016071000_commerce_sales_abc_window_v1.sql');
const adSql=read('supabase/migrations/20261016072000_commerce_sales_abc_ads_window_v1.sql');
const store=read('src/commerce-supabase-store.js');
const router=read('src/commerce-admin-router.js');
const css=read('src/commerce-commercial-dashboard.css');
test('one universal filter controls platform and real days for the commercial overview, ABC and performance',()=>{
  assert.match(dashboard,/nisti-com-global-filters/);
  assert.match(dashboard,/Últimos \{n\} dias/);
  assert.match(dashboard,/onChange=\{e=>\{setDays\(Number\(e\.target\.value\)\)/);
  assert.match(dashboard,/type="month" value=\{referenceMonth\}/);
  assert.match(dashboard,/value=\{platform\}/);
  assert.match(dashboard,/<CommerceSalesVelocity platform=\{platform\} days=\{days\} month=\{referenceMonth\}/);
  assert.match(dashboard,/fetchJson\('\/api\/admin\/commerce\/sales\/abc\/window\?'\+p\)/);
  assert.match(dashboard,/days=\{days\}/);
  assert.match(dashboard,/month=\{referenceMonth\}/);
  assert.match(abc,/\/sales\/abc\/advertisements\/window\?/);
  assert.doesNotMatch(dashboard,/nisti-com-products-filters/);
});
test('compact dashboard still provides manual import and catalog search without changing mobile framing',()=>{
  assert.match(dashboard,/setImportOpen\(v=>!v\)/);
  assert.match(dashboard,/importOpen&&<CommerceImportCenter embedded/);
  assert.match(dashboard,/externalSearch=\{debouncedSearch\}/);
  assert.match(dashboard,/className="nisti-com-global-search"/);
  assert.match(css,/\.nisti-com-metric\{min-height:84px/);
  assert.match(css,/\.nisti-com-abc-card\{min-height:110px/);
  assert.doesNotMatch(css,/\.nisti-com-abc-cards\{grid-template-columns:1fr;\}/);
});
test('sales 7/30/60/90-day facts come from committed listing records, not monthly snapshots',()=>{
  assert.match(sql,/commerce_current_sales_listing_daily_v1/);
  assert.match(sql,/commerce_sales_import_stage_summary/);
  assert.match(sql,/b.status='COMMITTED'/);
  assert.match(sql,/d.sale_date between w.previous_start and w.current_end/);
  assert.match(sql,/where l.listing_status='ACTIVE'/);
  assert.match(sql,/covered_sources/);
  assert.match(sql,/sources_missing/);
  assert.match(sql,/current_days>=w.days/);
  assert.doesNotMatch(sql,/insert into public\.products|delete from public\.products/);
  assert.match(store,/commerce_sales_velocity_v2/);
});
test('ABC classification and advertisement drilldown use precisely the same selected days',()=>{
  assert.match(abcSql,/commerce_sales_velocity_v2\(p_days,p_platform,p_reference_month,'ALL',1,0\)/);
  assert.match(abcSql,/commerce_current_sales_listing_daily_v1/);
  assert.match(abcSql,/p_days integer default 30/);
  assert.match(adSql,/commerce_sales_abc_window_v1\(p_platform,p_days,p_reference_month,p_basis\)/);
  assert.match(adSql,/s.sale_date between i.start_date and i.end_date/);
  assert.match(adSql,/'imported_units',imported_units/);
  assert.match(router,/\/sales\/abc\/window/);
  assert.match(router,/\/sales\/abc\/advertisements\/window/);
  assert.match(store,/commerce_sales_abc_ads_window_v1/);
  assert.match(velocity,/statusMap/);
});
