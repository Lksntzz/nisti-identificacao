CREATE INDEX idx_cover_reference_embeddings_updated_at ON public.cover_reference_embeddings(updated_at);
CREATE INDEX idx_cover_visual_signatures_reference ON public.cover_visual_signatures(reference_id);
CREATE INDEX idx_notifications_created ON public.notifications(created_at DESC);
CREATE INDEX idx_notifications_capa_normalized ON public.notifications((upper(btrim(capa_code))));
CREATE INDEX idx_notification_reads_user ON public.notification_reads(user_id, notification_id);
CREATE INDEX idx_scan_occurrences_status_created_at ON public.scan_occurrences(status, created_at DESC);
CREATE INDEX idx_geometric_shadow_evidence_photo ON public.geometric_shadow_evidence(platform, photo_sha256);
CREATE INDEX idx_geometric_shadow_evidence_occurrence ON public.geometric_shadow_evidence(occurrence_id);
CREATE INDEX idx_geometric_shadow_evidence_confirmed ON public.geometric_shadow_evidence(confirmed_capa_code, confirmed_at);
CREATE INDEX idx_geometric_shadow_evidence_independent ON public.geometric_shadow_evidence(content_independent, confirmed_at);

