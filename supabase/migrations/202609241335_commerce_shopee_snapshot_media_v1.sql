create or replace function public.commerce_list_shopee_snapshot_v1(
  p_search text default null,
  p_match_status text default null,
  p_limit integer default 50,
  p_offset integer default 0
)
returns table(
  snapshot_id bigint,
  external_listing_id text,
  parent_sku text,
  title text,
  marketplace_category text,
  cover_image_url text,
  product_image_urls jsonb,
  variation_name text,
  variation_options jsonb,
  listing_id bigint,
  match_status text,
  canonical_url text,
  listing_status text,
  product_count bigint,
  snapshot_key text,
  ingested_at timestamptz,
  total_count bigint
)
language sql
stable
security invoker
set search_path=public
as $$
  with latest as (
    select distinct on (s.external_listing_id)
      s.*
    from public.commerce_marketplace_snapshots s
    join public.commerce_marketplaces m on m.id=s.marketplace_id
    where upper(m.code)='SHOPEE'
    order by s.external_listing_id,s.ingested_at desc,s.id desc
  ), filtered as (
    select
      s.id snapshot_id,s.external_listing_id,s.parent_sku,s.title,s.marketplace_category,
      s.cover_image_url,s.product_image_urls,s.variation_name,s.variation_options,
      s.listing_id,s.match_status,l.canonical_url,l.listing_status,
      count(distinct lp.product_id) filter (where lp.relation_status<>'REMOVED') as product_count,
      s.snapshot_key,s.ingested_at
    from latest s
    left join public.commerce_listings l on l.id=s.listing_id
    left join public.commerce_listing_products lp on lp.listing_id=l.id
    where (nullif(btrim(coalesce(p_match_status,'')),'') is null or s.match_status=upper(btrim(p_match_status)))
      and (
        nullif(btrim(coalesce(p_search,'')),'') is null
        or s.external_listing_id ilike '%'||btrim(p_search)||'%'
        or s.parent_sku ilike '%'||btrim(p_search)||'%'
        or s.title ilike '%'||btrim(p_search)||'%'
      )
    group by s.id,s.external_listing_id,s.parent_sku,s.title,s.marketplace_category,
      s.cover_image_url,s.product_image_urls,s.variation_name,s.variation_options,
      s.listing_id,s.match_status,l.canonical_url,l.listing_status,s.snapshot_key,s.ingested_at
  ), counted as (
    select f.*,count(*) over() total_count
    from filtered f
  )
  select *
  from counted
  order by case match_status when 'NEW_PENDING' then 0 when 'CONFLICT' then 1 else 2 end,
           lower(coalesce(title,'')),external_listing_id
  limit greatest(1,least(coalesce(p_limit,50),100))
  offset greatest(coalesce(p_offset,0),0);
$$;

