create or replace function public.commerce_ingest_shopee_snapshot_v1(
  p_items jsonb,
  p_snapshot_key text,
  p_source_account_id text,
  p_source_basic_filename text,
  p_source_media_filename text,
  p_source_basic_sha256 text,
  p_source_media_sha256 text
)
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_marketplace_id bigint;
  v_item jsonb;
  v_external_id text;
  v_listing_id bigint;
  v_listing_count integer;
  v_existing_external text;
  v_match_status text;
  v_matched integer := 0;
  v_pending integer := 0;
  v_conflicts integer := 0;
  v_title_updates integer := 0;
  v_external_id_fills integer := 0;
  v_old_title text;
  v_title text;
begin
  if jsonb_typeof(p_items) <> 'array' then
    raise exception 'items_must_be_array' using errcode = '22023';
  end if;
  if nullif(btrim(coalesce(p_snapshot_key,'')),'') is null then
    raise exception 'snapshot_key_required' using errcode = '22023';
  end if;

  select id into v_marketplace_id
  from public.commerce_marketplaces
  where upper(code) = 'SHOPEE'
  limit 1;

  if v_marketplace_id is null then
    raise exception 'shopee_marketplace_missing' using errcode = 'P0001';
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_external_id := nullif(btrim(coalesce(v_item->>'external_listing_id','')),'');
    if v_external_id is null or v_external_id !~ '^[0-9]+$' then
      raise exception 'external_listing_id_invalid' using errcode = '22023';
    end if;

    select count(*), min(l.id)
      into v_listing_count, v_listing_id
    from public.commerce_listings l
    where l.marketplace_id = v_marketplace_id
      and (
        l.external_listing_id = v_external_id
        or l.canonical_url ~ ('/(product/[0-9]+/|portal/product/)' || v_external_id || '([/?#]|$)')
      );

    v_match_status := case
      when v_listing_count = 0 then 'NEW_PENDING'
      when v_listing_count = 1 then 'MATCHED'
      else 'CONFLICT'
    end;

    if v_match_status = 'MATCHED' then
      select l.external_listing_id,l.title
        into v_existing_external,v_old_title
      from public.commerce_listings l
      where l.id = v_listing_id;

      if nullif(btrim(coalesce(v_existing_external,'')),'') is not null
         and v_existing_external <> v_external_id then
        v_match_status := 'CONFLICT';
      end if;
    end if;

    insert into public.commerce_marketplace_snapshots(
      marketplace_id,external_listing_id,snapshot_key,source_account_id,
      source_basic_filename,source_media_filename,source_basic_sha256,source_media_sha256,
      parent_sku,title,description,marketplace_category,cover_image_url,
      product_image_urls,variation_name,variation_options,failure_reason,
      listing_id,match_status,updated_at
    )
    values(
      v_marketplace_id,
      v_external_id,
      btrim(p_snapshot_key),
      nullif(btrim(coalesce(p_source_account_id,'')),''),
      nullif(btrim(coalesce(p_source_basic_filename,'')),''),
      nullif(btrim(coalesce(p_source_media_filename,'')),''),
      nullif(btrim(coalesce(p_source_basic_sha256,'')),''),
      nullif(btrim(coalesce(p_source_media_sha256,'')),''),
      nullif(btrim(coalesce(v_item->>'parent_sku','')),''),
      nullif(btrim(coalesce(v_item->>'title','')),''),
      v_item->>'description',
      nullif(btrim(coalesce(v_item->>'marketplace_category','')),''),
      nullif(btrim(coalesce(v_item->>'cover_image_url','')),''),
      case when jsonb_typeof(v_item->'product_image_urls')='array'
        then v_item->'product_image_urls' else '[]'::jsonb end,
      nullif(btrim(coalesce(v_item->>'variation_name','')),''),
      case when jsonb_typeof(v_item->'variation_options')='array'
        then v_item->'variation_options' else '[]'::jsonb end,
      nullif(btrim(coalesce(v_item->>'failure_reason','')),''),
      case when v_match_status='MATCHED' then v_listing_id else null end,
      v_match_status,
      now()
    )
    on conflict (marketplace_id,external_listing_id,snapshot_key)
    do update set
      source_account_id=excluded.source_account_id,
      source_basic_filename=excluded.source_basic_filename,
      source_media_filename=excluded.source_media_filename,
      source_basic_sha256=excluded.source_basic_sha256,
      source_media_sha256=excluded.source_media_sha256,
      parent_sku=excluded.parent_sku,
      title=excluded.title,
      description=excluded.description,
      marketplace_category=excluded.marketplace_category,
      cover_image_url=excluded.cover_image_url,
      product_image_urls=excluded.product_image_urls,
      variation_name=excluded.variation_name,
      variation_options=excluded.variation_options,
      failure_reason=excluded.failure_reason,
      listing_id=excluded.listing_id,
      match_status=excluded.match_status,
      updated_at=now();

    if v_match_status = 'MATCHED' then
      v_title := nullif(btrim(coalesce(v_item->>'title','')),'');
      if v_title is not null and v_old_title is distinct from v_title then
        v_title_updates := v_title_updates + 1;
      end if;
      if nullif(btrim(coalesce(v_existing_external,'')),'') is null then
        v_external_id_fills := v_external_id_fills + 1;
      end if;

      update public.commerce_listings
      set
        external_listing_id = coalesce(nullif(btrim(external_listing_id),''), v_external_id),
        title = coalesce(v_title,title),
        raw_metadata = coalesce(raw_metadata,'{}'::jsonb) || jsonb_build_object(
          'shopee_snapshot',
          jsonb_build_object(
            'snapshot_key',btrim(p_snapshot_key),
            'external_listing_id',v_external_id,
            'parent_sku',nullif(btrim(coalesce(v_item->>'parent_sku','')),''),
            'marketplace_category',nullif(btrim(coalesce(v_item->>'marketplace_category','')),''),
            'cover_image_url',nullif(btrim(coalesce(v_item->>'cover_image_url','')),''),
            'product_image_urls',case when jsonb_typeof(v_item->'product_image_urls')='array' then v_item->'product_image_urls' else '[]'::jsonb end,
            'variation_name',nullif(btrim(coalesce(v_item->>'variation_name','')),''),
            'variation_options',case when jsonb_typeof(v_item->'variation_options')='array' then v_item->'variation_options' else '[]'::jsonb end,
            'source_basic_filename',nullif(btrim(coalesce(p_source_basic_filename,'')),''),
            'source_media_filename',nullif(btrim(coalesce(p_source_media_filename,'')),''),
            'ingested_at',now()
          )
        ),
        updated_at=now()
      where id=v_listing_id;

      v_matched := v_matched + 1;
    elsif v_match_status='NEW_PENDING' then
      v_pending := v_pending + 1;
    else
      v_conflicts := v_conflicts + 1;
    end if;
  end loop;

  return jsonb_build_object(
    'snapshot_key',btrim(p_snapshot_key),
    'processed',jsonb_array_length(p_items),
    'matched',v_matched,
    'new_pending',v_pending,
    'conflicts',v_conflicts,
    'title_updates',v_title_updates,
    'external_id_fills',v_external_id_fills
  );
end;
$$;

