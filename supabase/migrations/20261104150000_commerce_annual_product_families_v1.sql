-- GA: familias comerciais por modelo e formato, independentes de capa e ano da edicao.
-- Nenhum Produto Mestre e associado automaticamente. Toda associacao exige revisao.
create table if not exists public.commerce_product_families_v1 (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 3 and 120),
  model_name text not null check (char_length(btrim(model_name)) between 2 and 120),
  format_name text not null check (char_length(btrim(format_name)) between 1 and 60),
  category_id bigint not null references public.commerce_categories(id),
  created_by text not null,
  updated_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists commerce_product_families_identity_v1_uq
  on public.commerce_product_families_v1
  (category_id, lower(btrim(model_name)), lower(btrim(format_name)));

create table if not exists public.commerce_product_family_members_v1 (
  product_id bigint primary key references public.commerce_products(id) on delete restrict,
  family_id bigint not null references public.commerce_product_families_v1(id) on delete restrict,
  evidence text not null check (char_length(btrim(evidence)) between 8 and 500),
  confirmed_by text not null,
  confirmed_at timestamptz not null default now()
);
create index if not exists commerce_product_family_members_family_v1_idx
  on public.commerce_product_family_members_v1(family_id, product_id);

create table if not exists public.commerce_product_family_events_v1 (
  id bigint generated by default as identity primary key,
  product_id bigint not null,
  family_id bigint not null,
  action text not null check (action in ('ASSIGN','UNASSIGN')),
  evidence text not null,
  actor text not null,
  created_at timestamptz not null default now()
);
create index if not exists commerce_product_family_events_product_v1_idx
  on public.commerce_product_family_events_v1(product_id, created_at desc);

alter table public.commerce_product_families_v1 enable row level security;
alter table public.commerce_product_family_members_v1 enable row level security;
alter table public.commerce_product_family_events_v1 enable row level security;
revoke all on public.commerce_product_families_v1, public.commerce_product_family_members_v1,
  public.commerce_product_family_events_v1 from public, anon, authenticated;
grant select, insert, update on public.commerce_product_families_v1 to service_role;
grant select, insert, delete on public.commerce_product_family_members_v1 to service_role;
grant select, insert on public.commerce_product_family_events_v1 to service_role;
grant usage, select on sequence public.commerce_product_families_v1_id_seq,
  public.commerce_product_family_events_v1_id_seq to service_role;

-- Busca administrativa com vinculacoes confirmadas; candidato sem familia continua visivel.
create or replace function public.commerce_product_family_catalog_v1(p_search text default null)
returns jsonb language sql stable security invoker set search_path to 'public' as $sql$
with q as (select lower(btrim(coalesce(p_search,''))) text),
families as (
  select f.id, f.name, f.model_name, f.format_name, f.category_id,
    c.name category_name, count(m.product_id)::int member_count
  from public.commerce_product_families_v1 f
  join public.commerce_categories c on c.id=f.category_id
  left join public.commerce_product_family_members_v1 m on m.family_id=f.id
  group by f.id,c.name
), candidates as (
  select p.id,p.name,p.temporal_type,p.edition_year,p.category_id,
    m.family_id, array_remove(array_agg(distinct s.sku),null) skus
  from public.commerce_products p
  cross join q
  left join public.commerce_product_family_members_v1 m on m.product_id=p.id
  left join public.commerce_product_skus s on s.product_id=p.id
  where char_length(q.text)>=2 and
    (position(q.text in lower(p.name))>0 or exists (
      select 1 from public.commerce_product_skus k
      where k.product_id=p.id and position(q.text in lower(k.sku))>0))
  group by p.id,m.family_id
  order by p.name,p.id limit 40
)
select jsonb_build_object(
  'families',coalesce((select jsonb_agg(to_jsonb(f) order by f.name,f.id) from families f),'[]'::jsonb),
  'categories',coalesce((select jsonb_agg(jsonb_build_object('id',c.id,'name',c.name) order by c.name)
                       from public.commerce_categories c where c.is_active),'[]'::jsonb),
  'members',coalesce((select jsonb_agg(jsonb_build_object(
    'family_id',m.family_id,'product_id',p.id,'name',p.name,'edition_year',p.edition_year,
    'temporal_type',p.temporal_type,'sku_count',(select count(*) from public.commerce_product_skus s where s.product_id=p.id),
    'confirmed_at',m.confirmed_at) order by p.name,p.id)
    from public.commerce_product_family_members_v1 m join public.commerce_products p on p.id=m.product_id),'[]'::jsonb),
  'candidates',coalesce((select jsonb_agg(to_jsonb(c)) from candidates c),'[]'::jsonb)
);
$sql$;
revoke all on function public.commerce_product_family_catalog_v1(text) from public,anon,authenticated;
grant execute on function public.commerce_product_family_catalog_v1(text) to service_role;

create or replace function public.commerce_product_family_save_v1(
  p_family_id bigint, p_name text, p_model text, p_format text, p_category_id bigint, p_actor text)
returns jsonb language plpgsql security invoker set search_path to 'public' as $sql$
declare v_id bigint;
begin
  if char_length(btrim(coalesce(p_name,''))) not between 3 and 120
    or char_length(btrim(coalesce(p_model,''))) not between 2 and 120
    or char_length(btrim(coalesce(p_format,''))) not between 1 and 60
    or char_length(btrim(coalesce(p_actor,''))) not between 2 and 120
    or p_category_id is null then
    raise exception 'Dados da familia invalidos.' using errcode='22023';
  end if;
  if not exists(select 1 from public.commerce_categories where id=p_category_id and is_active) then
    raise exception 'Categoria inexistente ou inativa.' using errcode='22023';
  end if;
  if p_family_id is null then
    insert into public.commerce_product_families_v1(name,model_name,format_name,category_id,created_by,updated_by)
    values(btrim(p_name),btrim(p_model),btrim(p_format),p_category_id,btrim(p_actor),btrim(p_actor))
    returning id into v_id;
  else
    -- Nao trocar categoria de familia com membros sem revisar todos os produtos.
    if exists(select 1 from public.commerce_product_family_members_v1 where family_id=p_family_id)
       and exists(select 1 from public.commerce_product_families_v1 where id=p_family_id and category_id<>p_category_id) then
      raise exception 'Remova os vinculos antes de trocar a categoria.' using errcode='22023';
    end if;
    update public.commerce_product_families_v1 set name=btrim(p_name),model_name=btrim(p_model),
      format_name=btrim(p_format),category_id=p_category_id,updated_by=btrim(p_actor),updated_at=now()
    where id=p_family_id returning id into v_id;
    if v_id is null then raise exception 'Familia nao encontrada.' using errcode='22023'; end if;
  end if;
  return jsonb_build_object('id',v_id,'saved',true);
end;
$sql$;
revoke all on function public.commerce_product_family_save_v1(bigint,text,text,text,bigint,text) from public,anon,authenticated;
grant execute on function public.commerce_product_family_save_v1(bigint,text,text,text,bigint,text) to service_role;

create or replace function public.commerce_product_family_member_set_v1(
  p_family_id bigint,p_product_id bigint,p_assign boolean,p_confirmed boolean,p_evidence text,p_actor text)
returns jsonb language plpgsql security invoker set search_path to 'public' as $sql$
declare v_category bigint; v_product_category bigint; v_existing bigint;
begin
  if p_confirmed is distinct from true or p_family_id is null or p_product_id is null
     or char_length(btrim(coalesce(p_evidence,''))) not between 8 and 500
     or char_length(btrim(coalesce(p_actor,''))) not between 2 and 120 then
    raise exception 'Confirmacao, produto e justificativa sao obrigatorios.' using errcode='22023';
  end if;
  select category_id into v_category from public.commerce_product_families_v1 where id=p_family_id;
  select category_id into v_product_category from public.commerce_products where id=p_product_id;
  if not found or v_category is null then raise exception 'Familia ou produto inexistente.' using errcode='22023'; end if;
  if p_assign and v_product_category is not null and v_product_category<>v_category then
    raise exception 'Categoria do produto diferente da familia.' using errcode='22023';
  end if;
  select family_id into v_existing from public.commerce_product_family_members_v1 where product_id=p_product_id for update;
  if p_assign then
    if v_existing is not null then
      if v_existing=p_family_id then return jsonb_build_object('ok',true,'unchanged',true); end if;
      raise exception 'Produto ja vinculado a outra familia. Revise antes de transferir.' using errcode='23505';
    end if;
    insert into public.commerce_product_family_members_v1(product_id,family_id,evidence,confirmed_by)
    values(p_product_id,p_family_id,btrim(p_evidence),btrim(p_actor));
  else
    if v_existing is distinct from p_family_id then
      raise exception 'Vinculo nao encontrado nesta familia.' using errcode='22023';
    end if;
    delete from public.commerce_product_family_members_v1 where product_id=p_product_id and family_id=p_family_id;
  end if;
  insert into public.commerce_product_family_events_v1(product_id,family_id,action,evidence,actor)
  values(p_product_id,p_family_id,case when p_assign then 'ASSIGN' else 'UNASSIGN' end,btrim(p_evidence),btrim(p_actor));
  return jsonb_build_object('ok',true,'assigned',p_assign);
end;
$sql$;
revoke all on function public.commerce_product_family_member_set_v1(bigint,bigint,boolean,boolean,text,text) from public,anon,authenticated;
grant execute on function public.commerce_product_family_member_set_v1(bigint,bigint,boolean,boolean,text,text) to service_role;
