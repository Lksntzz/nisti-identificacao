  end if;
  if v_action not in ('LISTING_STATUS','TITLE','OBSERVED_YEAR','IMAGE_URL','PRICE','CATEGORY','NOTE','TITLE_ADD','TITLE_REMOVE') then
    raise exception 'bulk_action_invalid' using errcode='22023';
  end if;

  for v_id in select distinct x from unnest(p_listing_ids) x where x is not null and x > 0 loop
    if v_action='TITLE_ADD' or v_action='TITLE_REMOVE' then
      select coalesce(o.title,l.title,'')
      into v_current_title
      from public.commerce_preview_listings l
      left join public.commerce_preview_listing_overrides o on o.listing_id=l.id
      where l.id=v_id;
      if not found then raise exception 'listing_not_found' using errcode='22023'; end if;
      if v_action='TITLE_ADD' then
        v_patch := jsonb_build_object('title',btrim(concat_ws(' ',v_current_title,nullif(btrim(coalesce(p_value,'')),''))));
      else
        v_patch := jsonb_build_object('title',btrim(replace(v_current_title,coalesce(p_value,''),'')));
      end if;
    elsif v_action='LISTING_STATUS' then v_patch := jsonb_build_object('listing_status',p_value);
    elsif v_action='TITLE' then v_patch := jsonb_build_object('title',p_value);
    elsif v_action='OBSERVED_YEAR' then v_patch := jsonb_build_object('observed_year',p_value);
    elsif v_action='IMAGE_URL' then v_patch := jsonb_build_object('image_url',p_value);
    elsif v_action='PRICE' then v_patch := jsonb_build_object('price',p_value);
    elsif v_action='CATEGORY' then v_patch := jsonb_build_object('category',p_value);
    else v_patch := jsonb_build_object('note',p_value);
    end if;
    perform public.commerce_preview_edit_listing_v1(v_id,v_patch,p_operator,v_batch);
    v_changed := v_changed + 1;
  end loop;

  return jsonb_build_object(
    'batch_token',v_batch,'requested_count',coalesce(array_length(p_listing_ids,1),0),
    'changed_count',v_changed,'action',v_action
  );
end;
$$;

create or replace function public.commerce_preview_queue_listing_sync_v1(
  p_listing_id bigint,
  p_operator text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_batch uuid := gen_random_uuid();
  v_before text;
begin
  if not exists (select 1 from public.commerce_preview_listings where id=p_listing_id) then
    raise exception 'listing_not_found' using errcode='22023';
  end if;

  select coalesce(sync_status,'NONE') into v_before
  from public.commerce_preview_listing_overrides where listing_id=p_listing_id;

  insert into public.commerce_preview_listing_overrides(listing_id,sync_status,updated_by,updated_at)
  values(p_listing_id,'PENDING',nullif(btrim(coalesce(p_operator,'')),''),now())
  on conflict(listing_id) do update set
    sync_status='PENDING',updated_by=excluded.updated_by,updated_at=now();

  insert into public.commerce_preview_listing_edit_history(
    batch_token,listing_id,field_name,old_value,new_value,operator_name
  ) values(
    v_batch,p_listing_id,'SYNC_STATUS',
    jsonb_build_object('sync_status',coalesce(v_before,'NONE')),
    jsonb_build_object('sync_status','PENDING'),
    nullif(btrim(coalesce(p_operator,'')),'')
  );

  return jsonb_build_object('listing_id',p_listing_id,'sync_status','PENDING','batch_token',v_batch);
end;
$$;

create or replace function public.commerce_preview_listing_editor_v1(p_listing_id bigint)
returns jsonb
language sql
stable
security invoker
set search_path = public
as $$
select jsonb_build_object(
  'listing_id',l.id,'marketplace_code',m.code,'marketplace_name',m.name,
  'external_listing_id',l.external_listing_id,'canonical_url',l.canonical_url,
  'base_title',l.title,'title',coalesce(o.title,l.title),
  'base_listing_status',l.listing_status,'listing_status',coalesce(o.listing_status,l.listing_status),
  'base_observed_year',l.observed_year,'observed_year',coalesce(o.observed_year,l.observed_year),
  'image_url',coalesce(
    o.image_url,
    (
      select nullif(sr.normalized_payload->>'image_url','')
      from public.commerce_preview_source_rows sr
      where sr.matched_listing_id=l.id and sr.is_header=false
        and nullif(sr.normalized_payload->>'image_url','') is not null
      order by sr.imported_at desc nulls last,sr.id desc
      limit 1
    )
  ),
  'price',coalesce(o.price,nullif(l.raw_metadata->>'price',''),nullif(l.raw_metadata->>'sale_price','')),
  'category',coalesce(o.category,nullif(l.raw_metadata->>'marketplace_category',''),nullif(l.raw_metadata->>'category','')),
  'note',o.note,'sync_status',coalesce(o.sync_status,'NONE'),
  'updated_by',o.updated_by,'updated_at',o.updated_at,
  'platform_skus',coalesce((
    select jsonb_agg(distinct coalesce(nullif(lp.platform_sku,''),ps.sku)) filter (where coalesce(nullif(lp.platform_sku,''),ps.sku) is not null)
    from public.commerce_preview_listing_products lp
    left join public.commerce_preview_product_skus ps on ps.id=lp.product_sku_id
    where lp.listing_id=l.id
  ),'[]'::jsonb),
  'products',coalesce((
    select jsonb_agg(jsonb_build_object(
      'product_id',p.id,'name',p.name,'platform_sku',lp.platform_sku,'variation_name',lp.variation_name
    ) order by p.name,p.id)
    from public.commerce_preview_listing_products lp
    join public.commerce_preview_products p on p.id=lp.product_id
    where lp.listing_id=l.id
  ),'[]'::jsonb),
  'history',coalesce((
    select jsonb_agg(jsonb_build_object(
      'id',h.id,'batch_token',h.batch_token,'field_name',h.field_name,
      'old_value',h.old_value,'new_value',h.new_value,'operator_name',h.operator_name,'created_at',h.created_at
    ) order by h.created_at desc,h.id desc)
    from (
      select * from public.commerce_preview_listing_edit_history
      where listing_id=l.id order by created_at desc,id desc limit 20
    ) h
  ),'[]'::jsonb)
)
from public.commerce_preview_listings l
join public.commerce_marketplaces m on m.id=l.marketplace_id
left join public.commerce_preview_listing_overrides o on o.listing_id=l.id
where l.id=p_listing_id;
$$;

create or replace function public.commerce_preview_enrich_management_platforms_v1(p_platforms jsonb)
returns jsonb
language sql
stable
security invoker
set search_path = public
as $$
select coalesce(jsonb_agg(
  p.platform || jsonb_build_object('items',coalesce(e.items,'[]'::jsonb))
  order by p.ord
),'[]'::jsonb)
from jsonb_array_elements(coalesce(p_platforms,'[]'::jsonb)) with ordinality p(platform,ord)
left join lateral (
  select jsonb_agg(
    i.item || jsonb_build_object(
      'listing_id',l.id,
      'listing_title',coalesce(o.title,l.title,i.item->>'product_name'),
      'listing_status',coalesce(o.listing_status,i.item->>'listing_status'),
      'edition_year',coalesce(o.observed_year,case when (i.item->>'edition_year') ~ '^[0-9]+$' then (i.item->>'edition_year')::integer end),
      'image_url',coalesce(o.image_url,nullif(i.item->>'image_url','')),
      'price',o.price,'listing_category',o.category,'listing_note',o.note,
      'sync_status',coalesce(o.sync_status,'NONE')
    )
    order by i.iord
  ) as items
  from jsonb_array_elements(coalesce(p.platform->'items','[]'::jsonb)) with ordinality i(item,iord)
  left join public.commerce_preview_source_rows sr
    on sr.id=case when (i.item->>'source_row_id') ~ '^[0-9]+$' then (i.item->>'source_row_id')::bigint end
  left join public.commerce_preview_listings l on l.id=sr.matched_listing_id
  left join public.commerce_preview_listing_overrides o on o.listing_id=l.id
) e on true;
$$;

