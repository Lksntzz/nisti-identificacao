create or replace function public.commerce_edit_listing_v1(
  p_listing_id bigint,
  p_patch jsonb,
  p_operator text default null,
  p_batch_token uuid default null
)
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_title text;
  v_status text;
  v_year integer;
  v_image text;
  v_price text;
  v_category text;
  v_note text;
  v_sync text;
  v_before jsonb;
  v_after jsonb;
  v_batch uuid := coalesce(p_batch_token, gen_random_uuid());
  v_fields text;
begin
  if p_listing_id is null or p_listing_id <= 0 then
    raise exception 'listing_id_invalid' using errcode='22023';
  end if;
  if p_patch is null or jsonb_typeof(p_patch) <> 'object' then
    raise exception 'patch_invalid' using errcode='22023';
  end if;
  if exists (
    select 1
    from jsonb_object_keys(p_patch) k(key)
    where k.key not in ('title','listing_status','observed_year','image_url','price','category','note')
  ) then
    raise exception 'patch_field_invalid' using errcode='22023';
  end if;

  select
    coalesce(o.title,l.title),
    coalesce(o.listing_status,l.listing_status),
    coalesce(o.observed_year,l.observed_year),
    o.image_url,
    o.price,
    o.category,
    o.note,
    coalesce(o.sync_status,'LOCAL')
  into v_title,v_status,v_year,v_image,v_price,v_category,v_note,v_sync
  from public.commerce_listings l
  left join public.commerce_listing_overrides o on o.listing_id=l.id
  where l.id=p_listing_id;

  if not found then
    raise exception 'listing_not_found' using errcode='22023';
  end if;

  v_before := jsonb_build_object(
    'title',v_title,'listing_status',v_status,'observed_year',v_year,
    'image_url',v_image,'price',v_price,'category',v_category,'note',v_note,
    'sync_status',v_sync
  );

  if p_patch ? 'title' then v_title := nullif(btrim(p_patch->>'title'),''); end if;
  if p_patch ? 'listing_status' then v_status := nullif(upper(btrim(p_patch->>'listing_status')),''); end if;
  if p_patch ? 'observed_year' then
    v_year := case when nullif(btrim(p_patch->>'observed_year'),'') is null then null else (p_patch->>'observed_year')::integer end;
  end if;
  if p_patch ? 'image_url' then v_image := nullif(btrim(p_patch->>'image_url'),''); end if;
  if p_patch ? 'price' then v_price := nullif(btrim(p_patch->>'price'),''); end if;
  if p_patch ? 'category' then v_category := nullif(btrim(p_patch->>'category'),''); end if;
  if p_patch ? 'note' then v_note := nullif(btrim(p_patch->>'note'),''); end if;

  if v_status is not null and v_status not in ('UNKNOWN','ACTIVE','PAUSED','INACTIVE','REMOVED') then
    raise exception 'listing_status_invalid' using errcode='22023';
  end if;
  if v_year is not null and (v_year < 2000 or v_year > 2100) then
    raise exception 'observed_year_invalid' using errcode='22023';
  end if;

  insert into public.commerce_listing_overrides(
    listing_id,title,listing_status,observed_year,image_url,price,category,note,sync_status,updated_by,updated_at
  ) values (
    p_listing_id,v_title,v_status,v_year,v_image,v_price,v_category,v_note,'LOCAL',
    nullif(btrim(coalesce(p_operator,'')),''),now()
  )
  on conflict (listing_id) do update set
    title=excluded.title,
    listing_status=excluded.listing_status,
    observed_year=excluded.observed_year,
    image_url=excluded.image_url,
    price=excluded.price,
    category=excluded.category,
    note=excluded.note,
    sync_status='LOCAL',
    updated_by=excluded.updated_by,
    updated_at=now();

  v_after := jsonb_build_object(
    'title',v_title,'listing_status',v_status,'observed_year',v_year,
    'image_url',v_image,'price',v_price,'category',v_category,'note',v_note,
    'sync_status','LOCAL'
  );

  select string_agg(key,',' order by key) into v_fields
  from jsonb_object_keys(p_patch) k(key);

  insert into public.commerce_listing_edit_history(
    batch_token,listing_id,field_name,old_value,new_value,operator_name
  ) values (
    v_batch,p_listing_id,coalesce(v_fields,'PATCH'),v_before,v_after,
    nullif(btrim(coalesce(p_operator,'')),'')
  );

  return v_after || jsonb_build_object('listing_id',p_listing_id,'batch_token',v_batch);
end;
$$;

create or replace function public.commerce_bulk_edit_listings_v1(
  p_listing_ids bigint[],
  p_action text,
  p_value text,
  p_operator text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_id bigint;
  v_action text := upper(btrim(coalesce(p_action,'')));
  v_patch jsonb;
  v_current_title text;
  v_batch uuid := gen_random_uuid();
  v_changed integer := 0;
begin
  if p_listing_ids is null or coalesce(array_length(p_listing_ids,1),0)=0 then
    raise exception 'listing_ids_required' using errcode='22023';
  end if;
  if v_action not in ('LISTING_STATUS','TITLE','OBSERVED_YEAR','IMAGE_URL','PRICE','CATEGORY','NOTE','TITLE_ADD','TITLE_REMOVE') then
    raise exception 'bulk_action_invalid' using errcode='22023';
  end if;

  for v_id in select distinct x from unnest(p_listing_ids) x where x is not null and x > 0 loop
    if v_action='TITLE_ADD' or v_action='TITLE_REMOVE' then
      select coalesce(o.title,l.title,'')
      into v_current_title
      from public.commerce_listings l
      left join public.commerce_listing_overrides o on o.listing_id=l.id
      where l.id=v_id;

      if not found then
        raise exception 'listing_not_found' using errcode='22023';
      end if;

      if v_action='TITLE_ADD' then
        v_patch := jsonb_build_object('title',btrim(concat_ws(' ',v_current_title,nullif(btrim(coalesce(p_value,'')),''))));
      else
        v_patch := jsonb_build_object('title',btrim(replace(v_current_title,coalesce(p_value,''),'')));
      end if;
    elsif v_action='LISTING_STATUS' then
      v_patch := jsonb_build_object('listing_status',p_value);
    elsif v_action='TITLE' then
      v_patch := jsonb_build_object('title',p_value);
    elsif v_action='OBSERVED_YEAR' then
      v_patch := jsonb_build_object('observed_year',p_value);
    elsif v_action='IMAGE_URL' then
      v_patch := jsonb_build_object('image_url',p_value);
    elsif v_action='PRICE' then
      v_patch := jsonb_build_object('price',p_value);
    elsif v_action='CATEGORY' then
      v_patch := jsonb_build_object('category',p_value);
    else
      v_patch := jsonb_build_object('note',p_value);
    end if;

    perform public.commerce_edit_listing_v1(v_id,v_patch,p_operator,v_batch);
    v_changed := v_changed + 1;
  end loop;

  return jsonb_build_object(
    'batch_token',v_batch,
    'requested_count',coalesce(array_length(p_listing_ids,1),0),
    'changed_count',v_changed,
    'action',v_action
  );
end;
$$;

create or replace function public.commerce_queue_listing_sync_v1(
  p_listing_id bigint,
  p_operator text default null
)
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_batch uuid := gen_random_uuid();
  v_before text;
begin
  if not exists (select 1 from public.commerce_listings where id=p_listing_id) then
    raise exception 'listing_not_found' using errcode='22023';
  end if;

  select coalesce(sync_status,'NONE') into v_before
  from public.commerce_listing_overrides
  where listing_id=p_listing_id;

  insert into public.commerce_listing_overrides(listing_id,sync_status,updated_by,updated_at)
  values(p_listing_id,'PENDING',nullif(btrim(coalesce(p_operator,'')),''),now())
  on conflict(listing_id) do update set
    sync_status='PENDING',
    updated_by=excluded.updated_by,
    updated_at=now();

  insert into public.commerce_listing_edit_history(
    batch_token,listing_id,field_name,old_value,new_value,operator_name
  ) values(
    v_batch,p_listing_id,'SYNC_STATUS',
    jsonb_build_object('sync_status',coalesce(v_before,'NONE')),
    jsonb_build_object('sync_status','PENDING'),
    nullif(btrim(coalesce(p_operator,'')),'')
  );

  return jsonb_build_object('listing_id',p_listing_id,'sync_status','PENDING','batch_token',v_batch);
end;
$$;

create or replace function public.commerce_listing_editor_v1(p_listing_id bigint)
returns jsonb
language sql
stable
security invoker
