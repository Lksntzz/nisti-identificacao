      from public.commerce_source_rows sr
      where sr.matched_listing_id=l.id
        and sr.is_header=false
        and nullif(sr.normalized_payload->>'image_url','') is not null
      order by sr.imported_at desc nulls last,sr.id desc
      limit 1
    )
  ),
  'price',coalesce(o.price,nullif(l.raw_metadata->>'price',''),nullif(l.raw_metadata->>'sale_price','')),
  'category',coalesce(o.category,nullif(l.raw_metadata->>'marketplace_category',''),nullif(l.raw_metadata->>'category','')),
  'note',o.note,
  'sync_status',coalesce(o.sync_status,'NONE'),
  'updated_by',o.updated_by,
  'updated_at',o.updated_at,
  'platform_skus',coalesce((
    select jsonb_agg(distinct coalesce(nullif(lp.platform_sku,''),ps.sku)) filter (where coalesce(nullif(lp.platform_sku,''),ps.sku) is not null)
    from public.commerce_listing_products lp
    left join public.commerce_product_skus ps on ps.id=lp.product_sku_id
    where lp.listing_id=l.id
  ),'[]'::jsonb),
  'products',coalesce((
    select jsonb_agg(jsonb_build_object(
      'product_id',p.id,'name',p.name,'platform_sku',lp.platform_sku,'variation_name',lp.variation_name
    ) order by p.name,p.id)
    from public.commerce_listing_products lp
    join public.commerce_products p on p.id=lp.product_id
    where lp.listing_id=l.id
  ),'[]'::jsonb),
  'history',coalesce((
    select jsonb_agg(jsonb_build_object(
      'id',h.id,'batch_token',h.batch_token,'field_name',h.field_name,
      'old_value',h.old_value,'new_value',h.new_value,
      'operator_name',h.operator_name,'created_at',h.created_at
    ) order by h.created_at desc,h.id desc)
    from (
      select *
      from public.commerce_listing_edit_history
      where listing_id=l.id
      order by created_at desc,id desc
      limit 20
    ) h
  ),'[]'::jsonb)
)
from public.commerce_listings l
join public.commerce_marketplaces m on m.id=l.marketplace_id
left join public.commerce_listing_overrides o on o.listing_id=l.id
where l.id=p_listing_id;
